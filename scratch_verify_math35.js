// 4名(s0, s1=0.5, s2, s3)
// ルール:
// 1. s1が休む日は、s0, s2, s3 のうち誰か1名が休む -> 実数 2.0
// 2. s1が出勤する日は、s0, s2, s3 のうち誰か1名が休む -> 実数 2.5
// 待て！
// 4人の公休日数の合計は 8 + 8 + 8 + 8 = 32日。
// s1の公休は 8日。
// s0, s2, s3 の公休合計は 8 * 3 = 24日。
// s1が休む8日間に、s0, s2, s3 がそれぞれ公休を取ると、その8日間に 8日分の公休が消費される。
// 残りの 20日間（s1が出勤する日）に、s0, s2, s3 の公休残りは 24 - 8 = 16日。
// 20日間のうち 16日は「s0, s2, s3 の誰か1名が休む」-> 実数 2.5！
// 残りの 4日間は「s0, s2, s3 の誰も休まない（全員出勤）」-> s1(0.5) + s0, s2, s3(3.0) = 3.5 になってしまう！
// あ！
// s1が出勤していて誰も休まないと 3.5 になってしまうのか！
// だから、添付2の合計実数は 67実数 なのか！
// 28日 × 4名 = 112。
// 出勤人数の合計が 77 だから、公休合計は 112 - 77 = 35日（32日ではない）！
// つまり、有休や公休追加で公休が 35日 ある！
// 35日公休の場合:
// 1日2人休む日が 7日、1日1人休む日が 21日。
// 7*2 + 21*1 = 14 + 21 = 35日！
// 0人休む日は 0日！
// すると、実数は 2.0 が 14日、2.5 が 14日、あるいは 2.0〜2.5 に完全に収まる！

