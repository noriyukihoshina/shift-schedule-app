// 28日間、毎日1人または2人が休む（0人休みは0日、2人休みは4日、1人休みは24日）
// s0, s1 (0.5), s2, s3
// s0とs1はスケ可なので被らない
// 2人休む日（4日間）は、必ず「s1(0.5) + (s0またはs2またはs3)」にする！
// そうすれば、s1が休む日は:
// 4日間は「s1 + 1.0の誰か」が休む -> 実数 1.0 + 1.0 = 2.0！
// 4日間は「s1だけ」が休む -> 実数 1.0 + 1.0 + 1.0 = 3.0... 待て、s1の公休は8日。
// もし 2人休む日を 8日間にしたらどうなるか？
// 4人の公休日数の合計は: 8 + 8 + 8 + 8 = 32日。
// 2人休む日が k 日、1人休む日が (28 - k) 日。
// 2*k + 1*(28 - k) = 32
// k + 28 = 32  =>  k = 4 日！！
// 数学的に、4人全員が8日公休（合計32日）を取る場合、
// 2人休む日は絶対に 4日 しか存在できない！！
// 残りの 24日は絶対に「1人だけ休む日」になる！！

// では、実数を計算してみよう：
// 1人休む日（24日）:
// - もし s1(0.5) が休んだら: 残り3人(全員1.0)が出勤 -> 実数 3.0！
// - もし 1.0 の誰かが休んだら: s1(0.5) + 1.0が2人出勤 -> 実数 2.5！
// 2人休む日（4日）:
// - もし s1(0.5) と 1.0の誰かが休んだら: 1.0が2人出勤 -> 実数 2.0！
// - もし 1.0の2人が休んだら: s1(0.5) + 1.0が1人出勤 -> 実数 1.5！

